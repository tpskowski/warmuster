// Assign Scouting deployment values to normalized army data and produce an
// auditable report for all shipped rule sets.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { applyCustomUnits } from "../src/data/customUnits.ts";
import { applyPlaytest2026 } from "../src/data/playtest2026.ts";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const baseFile = path.join(root, "src", "data", "generated", "warmaster-revolution.json");
const lookupFile = path.join(root, "src", "data", "generated", "scouting-points.json");
const reportFile = path.join(root, "reports", "scouting-points.md");

const FLYER_IDS = new Set([
  // These units fly by special rule but predate the normalized Flying subtype.
  "dogs-of-war:birdmen",
  "regiments-of-renown:birdmen-of-catrazza",
  "dwarfs:torgo-thungnisson-mounted",
]);
const FLYER_SCOUT_IDS = new Set([
  "dwarfs:rangers",
  "skaven:gutter-runners",
  "ogre-kingdoms:gorgers",
  "wood-elves:waywatchers",
]);
const SCOUT_IDS = new Set([
  "vampire-counts:ethereal-host",
  "witch-hunters:warhounds",
  "norse:huntsmen",
  "beastmen:gor",
  "beastmen:ungor",
  "empire:skirmishers",
  "dwarfs:ancestral-warriors",
]);
const PATROL_IDS = new Set(["skaven:rat-swarms", "lizardmen:skinks"]);

function isFlying(unit) {
  return unit.subType?.toLowerCase() === "flying" || FLYER_IDS.has(unit.unitId);
}

export function scoutingPointsFor(unit) {
  if (isFlying(unit) || FLYER_SCOUT_IDS.has(unit.unitId)) return 3;
  if (SCOUT_IDS.has(unit.unitId)) return 2;
  if (unit.type === "Cavalry" && unit.armour === "6+") return 2;
  if (unit.type === "General") return 2;
  if (PATROL_IDS.has(unit.unitId)) return 1;
  if (unit.type === "Cavalry" && (unit.armour == null || unit.armour === "5+")) return 1;
  if (unit.category === "character") return 1;
  return 0;
}

function assign(ruleSet) {
  for (const army of ruleSet.armies) {
    for (const unit of army.units) unit.scoutingPoints = scoutingPointsFor(unit);
  }
  return ruleSet;
}

function lookup(ruleSet) {
  return Object.fromEntries(
    ruleSet.armies.flatMap((army) =>
      army.units.map((unit) => [unit.unitId, unit.scoutingPoints]),
    ),
  );
}

function report(ruleSets) {
  const lines = [
    "# Scouting points report",
    "",
    "Generated by `npm run scouting:data`. Units are grouped by army and then by scouting points from 3 to 0.",
    "",
  ];
  for (const ruleSet of ruleSets) {
    lines.push(`# ${ruleSet.name}`, "");
    for (const army of ruleSet.armies) {
      lines.push(`## ${army.name}`, "");
      for (const points of [3, 2, 1, 0]) {
        const units = army.units
          .filter((unit) => unit.scoutingPoints === points)
          .sort((a, b) => a.troop.localeCompare(b.troop));
        lines.push(`### ${points} scouting points`, "");
        if (units.length === 0) lines.push("- None");
        else for (const unit of units) lines.push(`- ${unit.troop} (\`${unit.unitId}\`)`);
        lines.push("");
      }
    }
  }
  return lines.join("\n");
}

function main() {
  const revolution = assign(JSON.parse(fs.readFileSync(baseFile, "utf8")));
  fs.writeFileSync(baseFile, `${JSON.stringify(revolution, null, 2)}\n`);

  const custom = structuredClone(revolution);
  custom.id = "warmaster-custom";
  custom.name = "A Matter of Mustaches";
  applyCustomUnits(custom, revolution);
  assign(custom);

  const playtest = structuredClone(revolution);
  playtest.id = "wmr-2026-playtest";
  playtest.name = "WMR - 2026 Playtest";
  for (const army of playtest.armies) {
    army.ruleSet = playtest.id;
    for (const unit of army.units) unit.ruleSet = playtest.id;
  }
  applyPlaytest2026(playtest);
  assign(playtest);

  fs.writeFileSync(
    lookupFile,
    `${JSON.stringify({
      "warmaster-revolution": lookup(revolution),
      "wmr-2026-playtest": lookup(playtest),
      "warmaster-custom": lookup(custom),
    }, null, 2)}\n`,
  );
  fs.mkdirSync(path.dirname(reportFile), { recursive: true });
  fs.writeFileSync(reportFile, report([revolution, playtest, custom]));

  for (const ruleSet of [revolution, playtest, custom]) {
    const totals = [3, 2, 1, 0].map(
      (points) =>
        ruleSet.armies.flatMap((army) => army.units).filter((unit) => unit.scoutingPoints === points)
          .length,
    );
    console.log(`${ruleSet.name}: ${totals[0]} at 3, ${totals[1]} at 2, ${totals[2]} at 1, ${totals[3]} at 0.`);
  }
  console.log(`Wrote ${path.relative(root, lookupFile)} and ${path.relative(root, reportFile)}.`);
}

main();
